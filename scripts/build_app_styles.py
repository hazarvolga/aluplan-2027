#!/usr/bin/env python3
"""Compose app CSS from canonical design-system files and app-owned extensions.

Run the token generator first when tokens.json changes. This compositor preserves
cascade order and rewrites only self-hosted font URLs for Next.js public assets.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path('src/styles/globals.css')
SOURCES = (
    ('fonts.css', 'design-system/tokens/fonts.css'),
    ('primitives.css', 'design-system/tokens/primitives.css'),
    ('semantic.css', 'design-system/tokens/semantic.css'),
    ('component-aliases.css', 'design-system/tokens/component-aliases.css'),
    ('base.css', 'design-system/components/base.css'),
    ('typography.css', 'design-system/components/typography/typography.css'),
    ('layout.css', 'design-system/components/layout/layout.css'),
    ('actions.css', 'design-system/components/actions/actions.css'),
    ('surfaces.css', 'design-system/components/surfaces/surfaces.css'),
    ('forms.css', 'design-system/components/forms/forms.css'),
    ('navigation.css', 'design-system/components/navigation/navigation.css'),
    ('disclosure.css', 'design-system/components/disclosure/disclosure.css'),
    ('feedback.css', 'design-system/components/feedback/feedback.css'),
    ('patterns.css', 'design-system/components/patterns/patterns.css'),
    ('preview.css', 'design-system/ui_kits/homepage/preview.css'),
    ('responsive.generated.css', 'design-system/components/responsive.generated.css'),
    ('application.css', 'src/styles/application.css'),
)
HEADER = '/* GENERATED by scripts/build_app_styles.py. Edit canonical design-system sources or src/styles/application.css, then run pnpm styles:generate. */\n'


BORDER_PROPERTY = re.compile(r'^(?:border(?:-(?:top|right|bottom|left|block|inline)(?:-(?:start|end))?)?(?:-width)?|border-image-width)$')
POSITION_PROPERTY = re.compile(r'^(?:top|right|bottom|left)$')
MARGIN_PROPERTY = re.compile(r'^margin(?:-(?:top|right|bottom|left|block|inline)(?:-(?:start|end))?)?$')
METRIC_PROPERTY = re.compile(r'^(?:font-size|font-weight|line-height|letter-spacing|border-radius|border-width|(?:row-|column-)?gap|padding(?:-(?:top|right|bottom|left|block|inline)(?:-start|-end)?)?)$')


def validate_application_transforms(source):
    """Allow semantic transform variables plus two selector-bound functional literals."""
    raw = []
    for match in re.finditer(r'(?:^|[;{}])\s*transform\s*:\s*([^;{}]+)', source, re.I):
        value = match.group(1).strip()
        if re.fullmatch(r'var\(--[\w-]+\)', value):
            continue
        raw.append(value)

    expected = ['rotate(180deg)', 'translate(-50%, -50%)']
    if not raw:
        return
    if sorted(raw) != expected:
        raise ValueError('Raw application transform: use a semantic token')

    contracts = {
        '.alu-pathway-glow': 'translate(-50%, -50%)',
        '.alu-faq-item[open] .alu-faq-item__chevron': 'rotate(180deg)',
    }
    for selector, expected_value in contracts.items():
        blocks = re.findall(rf'(?m)^[\t ]*{re.escape(selector)}[\t ]*\{{([^{{}}]*)\}}', source)
        values = [value.strip() for block in blocks for value in re.findall(
            r'(?m)^\s*transform\s*:\s*([^;]+);', block
        )]
        if values != [expected_value]:
            raise ValueError('Raw application transform: functional literal moved outside its selector contract')


def validate_application_metrics(source, defined_vars=None):
    """Guard migrated design properties; structural zeros and layout rules remain valid."""
    source = re.sub(r'/\*[\s\S]*?\*/', '', source)
    defined_vars = defined_vars or set()
    skip_link_rule = re.compile(r'(^|})\s*\.alu-skip-link\s*\{([^{}]*)\}', re.M)
    source = skip_link_rule.sub(lambda match: match.group(1) + '.alu-skip-link {' + re.sub(
        r'(?<![\w-])left\s*:\s*-9999px\s*;?', '', match.group(2), flags=re.I
    ) + '}', source)
    for match in re.finditer(r'(?:^|[;{}])\s*([a-z-]+)\s*:\s*([^;{}]+)', source, re.I):
        prop, value = match.groups()
        if prop.lower() in {'filter', 'backdrop-filter', '-webkit-backdrop-filter'}:
            if not re.fullmatch(r'var\(--filter-[\w-]+\)', value.strip()):
                raise ValueError('Raw application filter: use a semantic filter token')
            continue
        if prop.lower() == 'box-shadow':
            token = re.fullmatch(r'var\((--(?:shadow|elevation)-[\w-]+)\)', value.strip())
            if not token or token.group(1) not in defined_vars:
                raise ValueError('Raw application shadow: use a semantic shadow or elevation token')
            continue
        if BORDER_PROPERTY.fullmatch(prop.lower()):
            unit_pattern = r'[a-zA-Z]+\b|%' if prop.lower() == 'border-image-width' else r'[a-zA-Z]+\b'
            widths = re.findall(r'(?<![\w.-])(-?(?:\d*\.)?\d+)(?:' + unit_pattern + r')', value, re.I)
            if any(float(width) != 0 for width in widths):
                raise ValueError(f'Raw application metric: {prop}; use a semantic token')
            continue
        if POSITION_PROPERTY.fullmatch(prop.lower()):
            offsets = re.findall(r'(?<![\w.-])(-?(?:\d*\.)?\d+)(?:px|rem|em|vw|vh|vmin|vmax)\b', value, re.I)
            if any(float(offset) != 0 for offset in offsets):
                raise ValueError(f'Raw application metric: {prop}; use a semantic token')
            continue
        if MARGIN_PROPERTY.fullmatch(prop.lower()):
            margins = re.findall(r'(?<![\w.-])(-?(?:\d*\.)?\d+)(?:px|rem|em|vw|vh|vmin|vmax)\b', value, re.I)
            if any(float(margin) != 0 for margin in margins):
                raise ValueError(f'Raw application metric: {prop}; use a semantic token')
            continue
        value = re.sub(r'var\([^)]*\)', '', value)
        if METRIC_PROPERTY.fullmatch(prop.lower()):
            numbers = re.findall(r'(?<![a-z-])-?(?:\d*\.)?\d+(?:[a-z%]+)?', value, re.I)
            if any(float(re.match(r'-?(?:\d*\.)?\d+', number).group()) != 0 for number in numbers):
                raise ValueError(f'Raw application metric: {prop}; use a semantic token')
        elif prop.lower().startswith(('transition', 'animation')):
            if re.search(r'(?<![a-z-])(?:\d*\.)?\d+(?:ms|s)\b|\b(?:cubic-bezier|steps)\(', value, re.I):
                raise ValueError(f'Raw application metric: {prop}; use motion tokens')


def validate_preview_literals(source):
    """Reject design-bearing literals in the production homepage preview layer."""
    source = re.sub(r'/\*[\s\S]*?\*/', '', source)
    if re.search(r'#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(', source, re.I):
        raise ValueError('Raw preview color: use a semantic token from tokens.json')
    if re.search(r'@media[^\{]*\b(?:min|max)-width\s*:\s*[\d.]', source, re.I):
        raise ValueError('Raw preview width media query: use responsive.template.css')
    if re.search(r'\bz-index\s*:\s*-?\d+', source, re.I):
        raise ValueError('Raw preview z-index: use a semantic token')

    for match in re.finditer(r'(?:^|[;{}])\s*([a-z-]+)\s*:\s*([^;{}]+)', source, re.I):
        prop, value = match.groups()
        value_without_tokens = re.sub(r'var\([^)]*\)', '', value)
        lengths = re.findall(
            r'(?<![\w.-])(-?(?:\d*\.)?\d+)(?:px|rem|em|vw|vh|vmin|vmax|ch)\b',
            value_without_tokens,
            re.I,
        )
        if any(float(length) != 0 for length in lengths):
            raise ValueError(f'Raw preview metric: {prop}; use a semantic token')


def build_styles(root=ROOT):
    """Read all inputs before writing; the tuple order is the app cascade contract."""
    parts = []
    canonical_vars = set()
    for label, relative in SOURCES:
        content = (root / relative).read_text(encoding='utf-8')
        if label in {'semantic.css', 'component-aliases.css'}:
            canonical_vars.update(re.findall(r'(--[\w-]+)\s*:', content))
        if label == 'preview.css':
            validate_preview_literals(content)
        if label == 'application.css':
            source = re.sub(r'/\*[\s\S]*?\*/', '', content)
            if re.search(r'#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(', source, re.IGNORECASE):
                raise ValueError('Raw application color: use a semantic token from tokens.json')
            validate_application_transforms(source)
            validate_application_metrics(source, canonical_vars)
        if label == 'fonts.css':
            content = content.replace('../assets/fonts/', '/assets/fonts/')
        parts.append(f'/* === {label} === */\n{content.rstrip()}\n')
    return HEADER + '\n'.join(parts)


def sync_styles(root=ROOT, check=False):
    content = build_styles(root)
    output = root / OUTPUT
    existing = output.read_text(encoding='utf-8') if output.is_file() else None
    if existing == content:
        return True
    if check:
        return False
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding='utf-8')
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Read-only drift check')
    args = parser.parse_args()
    try:
        matches = sync_styles(check=args.check)
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, f'App styles failed: {error}\n')
    if not matches:
        parser.exit(1, 'App styles drift: regenerate with pnpm styles:generate\n')
    print('App styles: canonical sources match' if args.check else 'App styles: generated')


if __name__ == '__main__':
    main()
